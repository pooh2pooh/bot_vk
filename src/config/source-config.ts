import type { TextMode } from '../core/text-mode.js';

/**
 * Декларативное описание одного источника из `config/sources.yml`.
 *
 * Источник полностью описывается здесь: добавить, убрать или перенастроить его —
 * правка YAML, без кода, пока используются уже зарегистрированные `type`,
 * `site` и `enrich`.
 *
 * Обязательные поля — ровно те, без которых источник не имеет смысла.
 * Опциональных полей с «догадками» здесь нет: каждое необязательное поле
 * имеет явный дефолт в `sources-loader.ts`, а не выводится из соседнего.
 * Иначе опечатка в YAML молча превращалась в другой источник, а не в ошибку.
 */
export interface SourceConfig {
  /** Уникальный id источника. Используется в БД, командах, логах. */
  id: string;

  /** Человекочитаемое имя для логов и команд. */
  name: string;

  /**
   * Тип адаптера: `rss`.
   * Определяет, КАК читаем источник. См. SourceAdapterRegistry.
   */
  type: string;

  /**
   * Стратегия сайта: `lor`, `pingvinus` или `none`.
   * Определяет, ЧТО делаем с записью: как достаём картинки и как чистим
   * описание. См. SiteStrategyRegistry.
   */
  site: string;

  /** Включён ли источник. Переключается также командой `/source`. */
  enabled: boolean;

  /** Адрес RSS/Atom-фида. */
  url: string;

  /**
   * Требовать ли хотя бы одну картинку.
   *
   * `true` для источников, где пост без картинки не имеет смысла
   * (скриншоты, релизы). `false` для лент новостей: там запись без картинки —
   * обычное дело, и выбрасывать её жалко.
   */
  requireImages: boolean;

  /** Ключ обогащения: `openrouter` или `none`. См. EnricherRegistry. */
  enrich: string;

  /** Что отправлять в сообщении. */
  textMode: TextMode;

  /** Путь к YAML-шаблону сообщения для этого источника. */
  template: string;

  /**
   * Длина текста фида в сообщении, символов.
   *
   * Применяется к режимам `feed` и `generated` (во втором — как fallback при
   * неудачной генерации). Укорачивание идёт по границе слова.
   */
  textLimit: number;

  /** Интервал опроса, мс. */
  pollIntervalMs: number;

  /** Таймаут HTTP-запросов к фиду и страницам постов, мс. */
  requestTimeoutMs: number;

  /**
   * Путь к промпту обогащения.
   *
   * Обязателен, если `enrich: openrouter`: у каждого источника своя задача
   * для модели (перевод анонса, разбор релиза), и общий промпт на все случаи
   * означал бы усреднение требований до безвкусного текста.
   */
  promptPath?: string;

  /**
   * Оставлять в фиде только посты, чей ЗАГОЛОВОК подходит под шаблон.
   *
   * Пример: `'^\[Stable Update\]'` — тогда в ленту попадут только анонсы,
   * а обычные новости будут отброшены на входе, ещё до разбора страниц.
   * Без поля берутся все записи фида.
   *
   * Проверяется заголовок целиком, а не «заголовок + описание»: иначе `^`
   * в шаблоне никогда не сработал бы.
   */
  includeFilter?: string;

  /**
   * Генерировать текст по промпту ТОЛЬКО для постов с подходящим заголовком.
   *
   * Остальные посты источника уходят в обычном режиме `textMode`. Это то, что
   * нужно манифесту, где в один фид свалены и анонсы обновлений, и новости:
   * переводить с помощью модели надо только анонсы.
   */
  generateWhen?: string;
}