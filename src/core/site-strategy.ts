import type { FeedItem } from './feed-item.js';
import { itemHtmlContent } from './feed-item.js';

/**
 * Единая стратегия одного сайта.
 *
 * Раньше такие вещи описывались двумя независимыми контрактами — списком
 * URL картинок и функцией чистки описания — которые реестры затем связывали
 * по имени ключа. Связка «два реестра по одному ключу» как раз и требует
 * ручной поддержки: добавить сайт значило зарегистрировать его дважды, а
 * забыть вторую половину молча ломало описание поста.
 *
 * Теперь контракт один: стратегия знает сайт целиком и отвечает за обе
 * стороны. Регистрация одна, ключ один, расхождение невозможно по построению.
 *
 * Чего стратегия НЕ делает: не ходит за пределы одного поста, не решает
 * что показывать AI, не знает про SQLite, шаблоны и VK. Это работа
 * конвейера — см. `core/source-adapter.ts` и `pipeline/source-pipeline.ts`.
 */
export interface SiteStrategy {
  /**
   * Картинки поста из элемента фида.
   *
   * Асинхронный метод не для красоты: фиды бывают lossy, и стратегии
   * разрешено догружать недостающее со страницы поста (так ведёт себя RSS
   * linux.org.ru — в описании лежит только первая картинка галереи).
   */
  images(item: FeedItem): Promise<string[]>;

  /**
   * Описание поста из элемента фида — сырая разметка, очисткой занимается
   * адаптер. Синхронный метод: чистка разметки не ходит в сеть.
   */
  description(item: FeedItem): string;

  /**
   * Картинки по прямой ссылке, без элемента фида.
   *
   * Нужно переотправке (`/source resend-last`): записи в базе старше окна
   * фида, в RSS их просто нет, а страница поста доступна всегда.
   */
  imagesFromUrl?(url: string): Promise<string[]>;

  /**
   * Исходный текст поста со страницы.
   *
   * Нужен, когда в фиде описание пустое (так отдаёт pingvinus) — иначе в
   * сообщение ушёл бы один заголовок. Используется как fallback, когда
   * генерация текста не удалась.
   */
  postText?(url: string): Promise<string>;
}

/**
 * Стратегия сайта, у которого в фиде разбирать нечего.
 * Зарегистрирована под ключом `none` и стоит по умолчанию.
 */
export const PLAIN_SITE_STRATEGY: SiteStrategy = {
  images: async () => [],
  description: item => itemHtmlContent(item)
};