import type { FeedEntry } from './types.js';

export interface FetchOptions {
  /**
   * Id записей, которые конвейер уже обработал — их можно не разбирать.
   *
   * Отдаётся адаптеру ДО извлечения картинок, а не после: у части стратегий
   * извлечение ходит на страницу поста, и без подсказки каждый опрос оплачивал
   * бы десятки лишних HTTP-запросов к чужому сайту ради постов, которые
   * конвейер всё равно отбросил бы.
   */
  skipIds?: ReadonlySet<string>;
}

/**
 * Единственная точка входа для получения новых записей источника.
 * Всё остальное (дедупликация, обогащение, шаблоны, отправка, backoff)
 * — общий конвейер, не завязанный на конкретный сайт.
 *
 * Новый ТИП источника (не RSS/Atom, например Telegram-канал или Reddit)
 * реализуется этим интерфейсом и регистрируется в SourceAdapterRegistry
 * под новым ключом `type`. Остальной код не меняется.
 */
export interface SourceAdapter {
  readonly sourceId: string;
  fetch(options?: FetchOptions): Promise<FeedEntry[]>;
  /**
   * Переизвлекает картинки для уже сохранённой записи.
   *
   * Нужен resend'у: правила извлечения картинок со временем меняются (напр.
   * LOR перестал класть в RSS все скриншоты галереи), а в базе лежит результат
   * на момент сохранения. Без этого повторная отправка всегда шла бы со
   * старым списком вложений.
   *
   * `link` передаётся потому, что запись может быть старше окна фида: тогда
   * её нет в RSS, и переизвлечение идёт прямо со страницы поста.
   *
   * Опционально: адаптер, который не умеет переизвлекать (или достать
   * картинки не удалось), возвращает null — вызывающий код падает на
   * сохранённое значение.
   */
  reextractImages?(id: string, link?: string): Promise<string[] | null>;
}
