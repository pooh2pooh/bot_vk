import he from 'he';

/**
 * Единственное место проекта, где HTML превращается в текст сообщения.
 *
 * Три разных реализации этого преобразования в проекте расходились по мелочам,
 * и разница была не видна: одни считали `&nbsp;`, другие нет; одни ставили
 * перенос только по закрывающим блочным тегам и склеивали «<h2>Заголовок</h2><p>Текст»
 * в «ЗаголовокТекст». Здесь правило одно.
 */

/** Первый непустой результат среди переданных строк. */
export function firstNonEmpty(
  ...values: Array<string | undefined | null>
): string | undefined {
  for (const value of values) {
    const trimmed = value?.trim();

    if (trimmed) {
      return trimmed;
    }
  }

  return undefined;
}

/**
 * Сырая разметка → текст: сущности, HTML, неразрывные пробелы, висячие
 * пробелы у переносов строк.
 */
export function toPlainText(markup: string): string {
  /*
   * Порядок важен: сначала снимаются НАСТОЯЩИЕ теги, потом раскрываются
   * сущности. Наоборот нельзя: раскрытый `&lt;b&gt;` стал бы настоящим `<b>`
   * и был бы вырезан вместе с разметкой — кусок текста поста исчез бы молча.
   */
  return fixSpaces(he.decode(stripDecodedMarkup(markup)));
}

/**
 * Неразрывный пробел приходит из `&nbsp;` и в сообщении выглядит слипшимся.
 *
 * Применяется ПОСЛЕ раскрытия сущностей: на сырой разметке там ещё `&nbsp;`,
 * а не сам символ. Замена записана явно через escape — неразрывный пробел
 * неотличим от обычного на глаз, и такая «уборка» молча превратилась бы в
 * замену пробела на пробел.
 */
const NON_BREAKING_SPACE = /\u00a0/g;

function fixSpaces(text: string): string {
  return text.replace(NON_BREAKING_SPACE, ' ');
}

/**
 * Разметка → текст БЕЗ раскрытия сущностей.
 *
 * Отдельная функция нужна там, где разметку пришлось раскрыть заранее: чтобы
 * разобрать вложенность блоков по исходным классам. Повторно раскрывать
 * сущности нельзя — текст вида `&amp;lt;b&amp;gt;` после двойного раскрытия
 * превратится в настоящие теги и будет вырезан вместе с разметкой.
 */
export function stripDecodedMarkup(markup: string): string {
  return markup
    // Перенос строки — и по <br>, и по блочным тегам в обе стороны.
    // Только закрывающих тегов мало: «<h2>Предыстория</h2><p>Текст» склеился бы
    // в «ПредысторияТекст».
    .replace(/<br\s*\/?>/gi, '\n')
    .replace(
      /<\/?(?:p|div|h[1-6]|li|ul|ol|blockquote|section|article|table|tr|figure|figcaption|pre)\b[^>]*>/gi,
      '\n'
    )
    .replace(/<[^>]*>/g, '')
    // Здесь разметка может быть как сырой, так и уже раскрытой.
    .replace(NON_BREAKING_SPACE, ' ')
    .replace(/[ \t]*\n[ \t]*/g, '\n')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}

/**
 * Укорачивает текст до `limit` символов, НЕ разрезая последнее слово.
 *
 * Обрыв на полуслове («...рабочий сто») теряет смысл, поэтому режем по
 * границе слова и ставим многоточие.
 *
 * Правила:
 *  - короче лимита — возвращается как есть;
 *  - режем по последнему пробелу в пределах лимита (минус многоточие);
 *  - пробела нет (один длинный токен, например URL) — режем жёстко, иначе
 *    получился бы бесконечный цикл;
 *  - многоточие добавляется только когда текст действительно обрезан.
 */
export function truncateText(value: string, limit: number): string {
  const text = value.trim();

  if (limit <= 0) {
    return '';
  }

  if (text.length <= limit) {
    return text;
  }

  const ellipsis = '…';
  const head = text.slice(0, limit - ellipsis.length);
  const lastSpace = head.lastIndexOf(' ');

  // lastSpace === -1 — пробела нет, режем жёстко, чтобы не зациклиться.
  const cut = lastSpace > 0 ? head.slice(0, lastSpace) : head;

  return `${cut.replace(/[\s.,;:!?—–-]+$/u, '')}${ellipsis}`;
}